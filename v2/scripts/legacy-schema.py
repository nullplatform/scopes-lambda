#!/usr/bin/env python3
"""Regenerates src/schema.ts and test/legacy-schema.json from ../lambda/specs/service-spec.json.tpl.

The legacy template is gomplate; this renders it the way the legacy publish does with
LAMBDA_DEPLOYMENT_TYPES=docker-image,zip and keeps the attributes schema byte for byte.
"""
import json
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
tpl = (root.parent / "lambda/specs/service-spec.json.tpl").read_text()
body = tpl[tpl.index('{\n  "available_actions"'):]
body = body.replace('"{{ $default }}"', '"docker-image"').replace('"{{ $assetDefault }}"', '"docker-image"')
body = re.sub(
    r'\{\{- range \$i, \$t := \$types \}\}\{\{ if \$i \}\},\{\{ end \}\}\s*'
    r'\{ "const": "\{\{ \$t \}\}", "title": "\{\{ index \$titles \$t \}\}" \}\s*\{\{- end \}\}',
    '{ "const": "docker-image", "title": "Docker Image (ECR)" },\n'
    '            { "const": "zip", "title": "ZIP Package (S3)" }',
    body,
)
body = body.replace('"{{ env.Getenv "NRN" }}"', '"<nrn>"')
schema = json.loads(body)["attributes"]["schema"]
ui = schema.pop("uiSchema")
(root / "test/legacy-schema.json").write_text(json.dumps({"schema": schema, "uiSchema": ui}, indent=2) + "\n")


def ts(obj):
    return json.dumps(obj, indent=2)


(root / "src/schema.ts").write_text(
    f'''/**
 * The attributes schema of the legacy `lambda` scope type (lambda/specs/service-spec.json.tpl,
 * rendered with LAMBDA_DEPLOYMENT_TYPES=docker-image,zip), kept byte for byte so existing scopes'
 * forms do not change, plus the read-only outputs the program records. Generated by
 * scripts/legacy-schema.py; do not edit by hand.
 */
import type {{ NpJSONSchema }} from "@nullplatform/plugin";
import type {{ ContextFor }} from "@nullplatform/plugin/package";

export const ASSET_TYPE = "docker-image";

/** What the program records after a successful run; shown on the scope, never editable. */
export const outputs = {{
  function_name: {{ type: "string", title: "Function name", readOnly: true, visibleOn: ["read"] }},
  function_arn: {{ type: "string", title: "Function ARN", readOnly: true, visibleOn: ["read"] }},
  alias_arn: {{ type: "string", title: "Alias ARN", readOnly: true, visibleOn: ["read"] }},
  execution_role_arn: {{ type: "string", title: "Execution role ARN", readOnly: true, visibleOn: ["read"] }},
  domain: {{ type: "string", title: "Domain", readOnly: true, visibleOn: ["read"] }},
  http_endpoint: {{ type: "string", title: "HTTP endpoint", readOnly: true, visibleOn: ["read"] }},
}} as const;

export const legacySchema = {ts(schema)} as const;

export const schema = {{
  ...legacySchema,
  properties: {{ ...legacySchema.properties, ...outputs }},
}} as const satisfies NpJSONSchema;

export const uiSchema = {ts(ui)} as const;

export type Context = ContextFor<typeof schema>;
export type Attributes = Context["params"];
'''
)
print(f"rendered {len(schema['properties'])} properties", file=sys.stderr)
